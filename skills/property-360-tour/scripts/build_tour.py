"""Put the tour together from home.json and the finished panoramas.

  python3 build_tour.py HOME.json TOUR_DIR                       writes TOUR_DIR/index.html and home.js; expects TOUR_DIR/panos/panoNN.jpg
  python3 build_tour.py HOME.json TOUR_DIR --standalone OUT.html also one file with everything inlined (opens by double-click)

Serve TOUR_DIR with any web server (python3 -m http.server) or hand over the standalone file. Only Three.js and the
font come from their CDNs.
"""
import base64
import json
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import home as homelib  # noqa: E402
import plan  # noqa: E402

if len(sys.argv) < 3:
    sys.exit(__doc__)
H = homelib.load(sys.argv[1])
out = sys.argv[2]
err, warn = H.validate()
if err:
    sys.exit("home.json has errors (python3 home.py HOME.json validate):\n  " + "\n  ".join(err))
os.makedirs(out, exist_ok=True)
markup, total = plan.svg(H, final=True)
data = dict(TITLE=H.TITLE, NOTE=H.NOTE, CEIL=H.CEIL,
            ROOMS=[dict(id=k, name=r["name"], poly=r["poly"]) for k, r in H.ROOMS.items()],
            NODES=[dict(n=p["n"], room=p["room"], x=p["x"], y=p["y"], h=p["h"], a=p.get("a", 0), cap=p.get("cap", "")) for p in H.NODES],
            LINKS=H.links(), DOORS=[dict(a=o["a"], b=o["b"], kind=o.get("kind")) for o in H.OPENINGS],
            TOTAL=round(total), PLAN_SVG=markup)
js = "// generated by build_tour.py from home.json (metres; x right, y down)\nwindow.HOME = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(out, "home.js"), "w", encoding="utf-8").write(js)
viewer = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "viewer", "index.html")
shutil.copy(viewer, os.path.join(out, "index.html"))
missing = [p["n"] for p in H.NODES if not os.path.exists(os.path.join(out, "panos", "pano%02d.jpg" % p["n"]))]
print(out, "tour written;", "missing panoramas for points %s" % missing if missing else "all %d panoramas present" % len(H.NODES))
if "--standalone" in sys.argv:
    dst = sys.argv[sys.argv.index("--standalone") + 1]
    if missing:
        sys.exit("cannot pack a standalone file while panoramas are missing")
    html = open(viewer, encoding="utf-8").read()
    panos = ",\n".join('  %d: "data:image/jpeg;base64,%s"' % (p["n"], base64.b64encode(open(os.path.join(out, "panos", "pano%02d.jpg" % p["n"]), "rb").read()).decode()) for p in H.NODES)
    tag = '<script src="home.js"></script>'
    assert tag in html
    open(dst, "w", encoding="utf-8").write(html.replace(tag, "<script>\n" + js + "window.PANOS = {\n" + panos + "\n};\n</script>"))
    print(dst, "%.1f MB" % (os.path.getsize(dst) / 1e6))
